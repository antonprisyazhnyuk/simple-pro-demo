/* Simple PRO — хаб «Покупателю» · механика шаблона.
   Один файл на все девять разделов: страница отличается только контентом,
   поведение у неё общее.

   §1 Лента разделов на мобе — подскролл активного пункта в видимую зону.
   §2 Расчёт срока доставки — живой контент раздела /customers/delivery/.
   §3 Правая колонка — где отпустить липкую панель (Доставка, Производство).
   ============================================================ */

(function () {
  "use strict";

  /* ── §1 ЛЕНТА: активный пункт в видимую зону ───────────────────────────────
     Лента живёт ВНИЗУ экрана, липкой, вплотную над моб-баром (слово Антона 04.08
     18:14) — раскладку держит css/mobile.css, здесь только подскролл.
     С девятью пунктами человек, открывший «Столешницы», иначе видит ленту с
     начала и не понимает, где он. Скроллим ТОЛЬКО саму ленту (scrollLeft), а не
     через scrollIntoView: тот тянет за собой и вертикальный скролл страницы —
     на длинных разделах это швыряет человека вниз при загрузке.
     Порог 720 читаем матчмедиа, а не шириной: он обязан совпадать с моб-сводом. */
  var rail = document.querySelector(".hub-nav");
  var active = rail && rail.querySelector(".hub-nav-item.is-active");
  var mobile = window.matchMedia("(max-width: 45rem)");

  function centerActive() {
    if (!rail || !active || !mobile.matches) return;
    var railBox = rail.getBoundingClientRect();
    var itemBox = active.getBoundingClientRect();
    // цель: активный пункт по центру ленты, но не левее нуля
    var target = rail.scrollLeft + (itemBox.left - railBox.left)
               - (railBox.width - itemBox.width) / 2;
    rail.scrollLeft = Math.max(0, target);
  }

  centerActive();
  // шрифты доезжают позже разметки и меняют ширины пунктов — пересчитываем
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(centerActive);
  mobile.addEventListener("change", centerActive);

  /* ── §2 РАСЧЁТ СРОКА ДОСТАВКИ ─────────────────────────────────────────────
     Живой контент раздела: выпадающий список городов, у каждого свой срок в днях.
     Данные лежат в разметке (data-days у <option>) — второго источника правды не
     заводим. Форма ничего не отправляет: это калькулятор, а не заявка.

     🔁 ВЫВОДИМ ГОЛОЕ ЧИСЛО — слово Антона 06.08 (наряд §6): слово «дней» убрать.
     Вместе с ним ушло и склонение: подпись «Срок доставки» стоит рядом постоянно,
     единицу измерения она и называет. Мёртвый расчёт формы слова здесь не оставляем —
     передумают, вернём из этой же строки истории, а не из закомментированного кода. */
  var pick = document.querySelector("[data-delivery-city]");
  var out = document.querySelector("[data-delivery-out]");
  if (pick && out) {
    var blank = out.textContent;
    // стартовое состояние — пустое: атрибут ставим сразу, иначе прочерк на первой
    // загрузке горит красным до первого выбора города
    out.toggleAttribute("data-empty", true);
    pick.addEventListener("change", function () {
      var opt = pick.options[pick.selectedIndex];
      var days = opt && opt.getAttribute("data-days");
      out.textContent = days ? String(parseInt(days, 10)) : blank;
      // пустое состояние приглушено: прочерк кеглем 52 фирменным красным читается как
      // сбой, а не как «город ещё не выбран» (кадр 06.08)
      out.toggleAttribute("data-empty", !days);
    });
  }

  /* ── §3 ПРАВАЯ КОЛОНКА: липнуть ли, и где отпустить ───────────────────────
     Две задачи, обе требуют замера живой геометрии — CSS ни ту, ни другую не решает.

     ① ЛИПНУТЬ ЛИ ВООБЩЕ. Панель выше окна липнуть не должна: прижатая, она прячет свой
     низ, а у формы «Гарантии» низ — это кнопка «Отправить» и строка согласия. Первая
     редакция вместо этого давала панели свою прокрутку (приём колонки разделов), и на
     ноутбучном окне 1440×900 внутрь уезжало 140 px, на 1280×760 — 262; по правому краю
     появлялась полоса, и на кадре это читалось как обрезанная панель (возврат приёмки
     06.08, Д6). Не влезает — едет со страницей целиком, без прокрутки и без обрезки.
     Сравниваем ПОЛНУЮ занимаемую высоту (верх посадки + панель + воздух снизу) с окном.

     ② ГДЕ ОТПУСТИТЬ. Панель липкая внутри своего трека (customers.css §ПРАВАЯ КОЛОНКА).
     Трек по умолчанию тянется до низа контент-колонки — «отпускается по низу своей
     секции». Двум разделам этого мало, и оба случая про ШИРОКИЙ блок под панелью: он
     идёт на всю колонку, то есть проходит и под самой панелью.

     Разметка объявляет намерение сама: `data-stick-to` — селектор блока-границы,
     `data-stick-at` — отпустить по его верху (start) или середине (center):
       · Производство — «до середины фотографии под ней, дальше отпускается»
         (прямое слово Антона 06.08) ⇒ center;
       · Доставка — карта проезда; прилипшая панель легла бы ей на правую половину,
         поэтому отпускаем ПЕРЕД картой ⇒ start (дефолт цеха, не слово Антона).

     ⚠ РАЗВОДА ПО ВЕРТИКАЛИ ЗДЕСЬ НЕТ, и это решение, а не упущение. Первая редакция
     сдвигала широкий блок вниз, чтобы он начинался под панелью: в макете над фото стоит
     текст, и фото туда не заезжает. Но в живом разделе «Производство» весь текст уехал
     в панель, левая колонка осталась с одним заголовком — и сдвиг превращался в 394 px
     белой пустоты между заголовком и телом. Наряд 06.08 §8 разрешил её прямым словом:
     «тело поднять под заголовок, пустоту убрать, выдумкой не заполнять». Значит фото
     начинается сразу под заголовком, а панель едет поверх него — на то она и карточка
     с собственным фоном (customers.css §ПРАВАЯ КОЛОНКА).

     CSS о том, где на странице начинается фото, знать неоткуда, — отсюда этот кусок.
     ⚠ Пиксели в стилях здесь не нарушение rem-канона: это не размер из макета, а замер
     живой геометрии. Переводить в rem вредно — ниже 1230 корень сам едет по vw, и
     записанное в rem число поехало бы вторично. */
  /* ⚠ Селектор БЕЗ `[data-stick-to]`: пункт ① нужен всем трём разделам с панелью, а
     границу объявляют только два. Прежняя выборка по атрибуту оставляла «Гарантию» —
     ту самую, где форма и не влезает, — вообще без присмотра. */
  var aside = document.querySelector(".hub-aside");
  var panel = aside && aside.querySelector(".hub-aside-panel");
  var stopSel = aside && aside.getAttribute("data-stick-to");
  var stopAt = stopSel ? document.querySelector(stopSel) : null;

  function layoutAside() {
    if (!aside || !panel) return;
    // мерим ВСЕГДА в естественном виде, иначе второй прогон считал бы от себя же
    aside.style.height = "";
    aside.classList.remove("is-tall");
    if (mobile.matches) return;            // на телефоне панель в потоке, липкости нет

    // ① влезает ли прилипшая панель в окно целиком.
    // Воздух снизу берём ИЗ САМОЙ панели — её `gap` объявлен тем же токеном --sp-24,
    // что и этот запас. Прежде здесь стоял множитель 1.5 от корневого кегля: число
    // верное, но связь с токеном держалась только комментарием, и правка --sp-24 молча
    // разъехалась бы с этим сравнением (находка свежего глаза 06.08).
    var cs = getComputedStyle(panel);
    var topPx = parseFloat(cs.top) || 0;
    var air = parseFloat(cs.rowGap) || 0;
    if (topPx + panel.offsetHeight + air > window.innerHeight) {
      aside.classList.add("is-tall");
      return;                              // не липнет — граница ей уже не нужна
    }

    // ② где отпустить
    if (!stopAt) return;
    var top = aside.getBoundingClientRect().top + window.scrollY;
    var box = stopAt.getBoundingClientRect();
    var ratio = aside.getAttribute("data-stick-at") === "center" ? 0.5 : 0;
    var stop = box.top + window.scrollY + box.height * ratio;
    if (stop > top) aside.style.height = (stop - top) + "px";
  }

  layoutAside();
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(layoutAside);
  mobile.addEventListener("change", layoutAside);
  // ресайз меняет и высоту панели, и место широкого блока — пересчитываем, но не чаще
  // кадра: замер вызывает reflow, а событий приходит десятки за одно перетаскивание
  var pending = false;
  window.addEventListener("resize", function () {
    if (pending) return;
    pending = true;
    requestAnimationFrame(function () { pending = false; layoutAside(); });
  });
})();
